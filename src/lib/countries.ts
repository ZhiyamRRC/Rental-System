const lookup = new Set<string>(countries);

/** Case-insensitive membership test used by the booking API. */
export function isValidCountry(value: string): boolean {
  if (lookup.has(value)) return true;
  const needle = value.trim().toLowerCase();
  return countries.some((c) => c.toLowerCase() === needle);
}
